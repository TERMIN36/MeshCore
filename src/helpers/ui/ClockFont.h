inline const char* clockNext(const char* s, uint16_t& cp) {
  uint8_t c = (uint8_t)s[0];
  if (c < 0x80) {
    cp = c;
    return s + 1;
  }
  if ((c & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
    cp = (uint16_t)(((c & 0x1F) << 6) | (uint8_t)(s[1] & 0x3F));
    return s + 2;
  }
  cp = c;
  return s + 1;
}

inline bool clockFind(const ClockFace& face, uint16_t ch, ClockGlyph& out) {
  for (uint8_t i = 0; i < face.count; i++) {
    memcpy_P(&out, face.glyphs + i, sizeof(ClockGlyph));
    if (out.ch == ch) return true;
  }
  return false;
}

inline int clockWidth(const ClockFace& face, const char* text) {
  int w = 0;
  for (const char* s = text; *s; ) {
    uint16_t cp;
    s = clockNext(s, cp);
    ClockGlyph g;
    if (clockFind(face, cp, g)) w += g.advance;
  }
  return w;
}

inline void clockInk(const ClockFace& face, const char* text, int& top, int& bot) {
  top = 127;
  bot = -127;
  for (const char* s = text; *s; ) {
    uint16_t cp;
    s = clockNext(s, cp);
    ClockGlyph g;
    if (!clockFind(face, cp, g) || g.h == 0) continue;
    if (g.top < top) top = g.top;
    int b = (int)g.top + g.h;
    if (b > bot) bot = b;
  }
  if (bot < top) { top = 0; bot = face.count ? 1 : 0; }
}
