# Font index order: А-Я (0..31), Ё (32), а-я (33..64), ё (65).
ORDER = [chr(c) for c in range(0x410, 0x430)] + ["Ё"] + [chr(c) for c in range(0x430, 0x450)] + ["ё"]


def glyph_rows(ch):
    top, *lines = CAPS.get(ch) or SMALL[ch]
    rows = [0] * H
    for i, line in enumerate(lines):
        assert len(line) == 5, (ch, line)
        rows[top + i] = sum(0x80 >> x for x, c in enumerate(line) if c == "#")
    return rows


def hex_block(values, fmt, per_line):
    items = [fmt % v for v in values]
    return ",\n".join("  " + ", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line))


def main():
    bits, offs = [], []
    for ch in ORDER:
        offs.append(len(bits))
        bits += glyph_rows(ch)
    n = len(ORDER)
    block = (
        "static const uint8_t CYR_OLED_H = %d;\n" % H
        + "static const uint8_t CYR_OLED_BASE = %d;\n" % BASE
        + "static const uint8_t CYR_OLED_ADV[%d] PROGMEM = {\n%s\n};\n" % (n, hex_block([ADV] * n, "0x%02X", 33))
        + "static const uint16_t CYR_OLED_OFF[%d] PROGMEM = {\n%s\n};\n" % (n, hex_block(offs, "0x%04X", 12))
        + "static const uint8_t CYR_OLED_BITS[%d] PROGMEM = {\n%s\n};\n" % (len(bits), hex_block(bits, "0x%02X", 16))
    )
    with open(INC, encoding="utf-8", newline="") as f:
        text = f.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    start = text.index("static const uint8_t CYR_OLED_H")
    end = text.index("static const uint8_t CYR_TFT_H")
    text = text[:start] + block.replace("\n", nl) + nl + text[end:]
    with open(INC, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote %d glyphs, %d bytes to %s" % (n, len(bits), INC))


if __name__ == "__main__":
    main()
